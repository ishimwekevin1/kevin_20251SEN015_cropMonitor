-- CSV-aware loader (Python csv module or SQL*Loader preprocessing) writes each
-- original row as JSON text. Season is supplied from the source filename.
-- This generic raw payload accommodates different A/B/C column sets.
CREATE TABLE stg_crop_production (
  staging_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  batch_id NUMBER NOT NULL REFERENCES import_batch(batch_id),
  season_code CHAR(1) NOT NULL CHECK(season_code IN ('A','B','C')),
  source_row_number NUMBER NOT NULL,
  raw_payload CLOB NOT NULL,
  staged_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  processing_status VARCHAR2(20) DEFAULT 'PENDING',
  processing_message VARCHAR2(1000),
  CONSTRAINT uq_stg_crop_row UNIQUE(batch_id,source_row_number)
);
CREATE INDEX ix_stg_crop_status ON stg_crop_production(batch_id,processing_status);
