-- Phase 0 logical schema starter. Refine column names after inspecting the NISR CSV.
CREATE TABLE season (
  season_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  season_name VARCHAR2(20) NOT NULL,
  agricultural_year VARCHAR2(20) NOT NULL,
  start_date DATE,
  end_date DATE,
  CONSTRAINT uq_season UNIQUE (season_name, agricultural_year)
);

CREATE TABLE geographic_area (
  area_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  province VARCHAR2(100) NOT NULL,
  district VARCHAR2(100) NOT NULL,
  sector VARCHAR2(100),
  CONSTRAINT uq_area UNIQUE (province, district, sector)
);

CREATE TABLE crop (
  crop_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  crop_name VARCHAR2(120) NOT NULL UNIQUE,
  crop_category VARCHAR2(80)
);

CREATE TABLE farm_type (
  farm_type_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  farm_type_name VARCHAR2(80) NOT NULL UNIQUE
);

CREATE TABLE production_record (
  record_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_record_key VARCHAR2(150) UNIQUE,
  season_id NUMBER NOT NULL REFERENCES season(season_id),
  area_id NUMBER NOT NULL REFERENCES geographic_area(area_id),
  crop_id NUMBER NOT NULL REFERENCES crop(crop_id),
  farm_type_id NUMBER REFERENCES farm_type(farm_type_id),
  harvest_quantity NUMBER(18,3) CHECK (harvest_quantity >= 0),
  remaining_quantity NUMBER(18,3) CHECK (remaining_quantity >= 0),
  harvested_area_ha NUMBER(18,4) CHECK (harvested_area_ha >= 0),
  yield_value NUMBER(18,4) CHECK (yield_value >= 0),
  seed_type VARCHAR2(100),
  seed_source VARCHAR2(100)
);

CREATE TABLE utilization (
  utilization_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id NUMBER NOT NULL UNIQUE REFERENCES production_record(record_id),
  consumed_quantity NUMBER(18,3) DEFAULT 0 CHECK (consumed_quantity >= 0),
  sold_quantity NUMBER(18,3) DEFAULT 0 CHECK (sold_quantity >= 0),
  stored_quantity NUMBER(18,3) DEFAULT 0 CHECK (stored_quantity >= 0),
  other_use_quantity NUMBER(18,3) DEFAULT 0 CHECK (other_use_quantity >= 0)
);

CREATE TABLE loss_record (
  loss_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  record_id NUMBER NOT NULL REFERENCES production_record(record_id),
  loss_stage VARCHAR2(40),
  loss_cause VARCHAR2(100),
  loss_quantity NUMBER(18,3) NOT NULL CHECK (loss_quantity >= 0)
);

CREATE TABLE import_audit (
  audit_id NUMBER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  source_file VARCHAR2(255) NOT NULL,
  imported_at TIMESTAMP DEFAULT SYSTIMESTAMP NOT NULL,
  rows_loaded NUMBER DEFAULT 0,
  rows_rejected NUMBER DEFAULT 0,
  loaded_by VARCHAR2(128) DEFAULT USER
);
